import os

import numpy as np
import tensorflow as tf

(x_train, y_train), (x_test, y_test) = tf.keras.datasets.mnist.load_data()
x_train = x_train.reshape(x_train.shape[0], 28*28)
x_test = x_test.reshape(x_test.shape[0], 28*28)

In = tf.keras.layers.Input(shape=(784,))
Cp1 = tf.keras.layers.Dense(64, activation='relu')(In)
Cp2 = tf.keras.layers.Dense(16, activation='relu')(Cp1) #El relu quita los valores que sean menores a 0
Out = tf.keras.layers.Dense(10, activation='softmax')(Cp2) #El softmax de vuelve un vector con probabilidades de pertencer a una clase [ 0, 0, 0, 0, 0, 0, 0, 0.7, 0, 0, 0.3, 0] esto nos puedes mostrar la seguridad del model, aunque esta seguridad no asegura que el modelo sea confiable
Model = tf.keras.Model(inputs=In, outputs=Out)

Model.summary()

Model.compile(optimizer='adam', loss='sparse_categorical_crossentropy', metrics=['accuracy'])

# ----------------- Normalizacion ÷255 (al final, antes de entrenar) -----------------
# Pasamos los pixeles de la escala 0-255 a 0-1 para que la red entrene mejor.
x_train = x_train / 255.0
x_test = x_test / 255.0
# ------------------------------------------------------------------------------------

Model.fit(x_train, y_train, epochs=30, batch_size=32)

# ----------------- Guardar el modelo entrenado (para usarlo en la interfaz) -----------------
# Se guarda en esta misma carpeta, con el nombre que carga interfaz_digit.py.
_ruta_modelo = os.path.join(os.path.dirname(os.path.abspath(__file__)), "modelo_mnist.keras")
Model.save(_ruta_modelo)
print(f"Modelo guardado en: {_ruta_modelo}")
